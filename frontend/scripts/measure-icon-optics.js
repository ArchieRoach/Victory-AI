// Optical alignment for icons. Run after adding a new lucide icon:
//   node scripts/measure-icon-optics.js
// (needs Playwright's Chromium; the App Store/cloud dev box has it.)
//
// Why: an icon centred by its box can still look off-centre. A play triangle's fat end is on the
// left, so its ink sits left of the middle and the icon looks pushed left. We draw every icon the
// app imports, find where its ink really sits, and nudge it so the ink lands in the middle: 3–6%
// of the icon's width, the usual optical nudge (smaller offsets are left alone, bigger ones capped).
// Writes src/theme/opticalIcons.json and the matching CSS block in src/index.css.
const fs = require("fs");
const path = require("path");
const React = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const Icons = require("lucide-react");

const SRC = path.join(__dirname, "..", "src");
const MIN = 3, MAX = 6;
// Icons that spin (a nudge would make them wobble).
const SKIP = new Set(["lucide-loader-circle", "lucide-loader", "lucide-refresh-cw"]);

function importedIcons() {
  const names = new Set();
  const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).forEach((e) => {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(jsx?|tsx?)$/.test(e.name)) {
      for (const m of fs.readFileSync(p, "utf8").matchAll(/import \{([^}]*)\} from "lucide-react"/g)) {
        m[1].split(",").map((s) => s.trim().split(/\s+as\s+/)[0]).filter(Boolean).forEach((n) => names.add(n));
      }
    }
  });
  walk(SRC);
  return [...names].sort();
}

function nudge(offset) {
  const a = Math.abs(offset);
  if (a < MIN) return 0;
  return Math.sign(offset) * Math.min(MAX, Math.round(a * 10) / 10);
}

function css(map) {
  const rules = Object.entries(map).sort(([a], [b]) => a.localeCompare(b))
    .map(([cls, [x, y]]) => `.${cls} { translate: ${x}% ${y}%; }`);
  return `/* optical-icons:start (generated by scripts/measure-icon-optics.js; do not edit by hand) */\n${rules.join("\n")}\n/* optical-icons:end */`;
}

async function main() {
  const { chromium } = require("playwright");
  const icons = importedIcons().filter((n) => Icons[n])
    .map((n) => {
      const markup = renderToStaticMarkup(React.createElement(Icons[n], { size: 240, color: "#000" }));
      const cls = (markup.match(/class="lucide ([^"]+)"/) || [])[1].split(" ").find((c) => c.startsWith("lucide-"));
      return { name: n, cls, markup };
    });
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM || "/opt/pw-browsers/chromium" });
  const page = await browser.newPage();
  const measured = await page.evaluate(async (list) => {
    const out = [];
    for (const s of list) {
      const img = new Image();
      img.src = "data:image/svg+xml;charset=utf-8," + encodeURIComponent(s.markup);
      await img.decode();
      const c = document.createElement("canvas"); c.width = c.height = 240;
      const g = c.getContext("2d"); g.drawImage(img, 0, 0);
      const d = g.getImageData(0, 0, 240, 240).data;
      let m = 0, sx = 0, sy = 0;
      for (let y = 0; y < 240; y++) for (let x = 0; x < 240; x++) { const a = d[(y * 240 + x) * 4 + 3]; m += a; sx += a * x; sy += a * y; }
      out.push({ ...s, dx: ((119.5 - sx / m) / 240) * 100, dy: ((119.5 - sy / m) / 240) * 100 });
    }
    return out;
  }, icons);
  await browser.close();

  const nudges = {};
  for (const i of measured) {
    if (SKIP.has(i.cls)) continue;
    const x = nudge(i.dx), y = nudge(i.dy);
    if (x || y) nudges[i.cls] = [x, y];
  }
  const json = { measured: icons.map((i) => i.name), nudges };
  fs.writeFileSync(path.join(SRC, "theme", "opticalIcons.json"), JSON.stringify(json, null, 1) + "\n");
  const cssPath = path.join(SRC, "index.css");
  const cur = fs.readFileSync(cssPath, "utf8");
  const block = css(nudges);
  const next = cur.includes("/* optical-icons:start")
    ? cur.replace(/\/\* optical-icons:start[\s\S]*?\/\* optical-icons:end \*\//, block)
    : `${cur}\n/* Icons: optical alignment (DESIGN.md §10). Each nudge moves an icon's ink to the middle of its box. */\n${block}\n`;
  fs.writeFileSync(cssPath, next);
  console.log(`Measured ${icons.length} icons; nudged ${Object.keys(nudges).length}.`);
}

module.exports = { nudge, css, MIN, MAX };
if (require.main === module) main();
